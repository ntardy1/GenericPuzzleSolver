std::vector<int> Problem1::solve(std::vector<int>& nums, int target) {
    for (int i = 0; i < nums.size(); i++){
        for (int j = i + 1; j < nums.size(); j++){
            if (i != j && nums.at(i) + nums.at(j) == target){
                return std::vector<int> {i, j};
            }
        }
    }
    return std::vector<int> {0, 0};
}